#!/usr/bin/env node
// Writes src/shopify-library/payment-icons.ts: the files Shopify's payment_type_svg_tag prints, from activemerchant/payment_icons (https://github.com/activemerchant/payment_icons, MIT, Copyright 2015 Shopify Inc; see NOTICE.md) at a pinned commit. The output is committed; run this again only to move to a new commit.
//
//   git clone https://github.com/activemerchant/payment_icons.git .local/payment_icons
//   git -C .local/payment_icons checkout fc8c830a5ca576553df88bf364fd449ea7b4f069
//   node bin/payment-icons.mjs .local/payment_icons
import { execFileSync } from 'node:child_process'
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const COMMIT = 'fc8c830a5ca576553df88bf364fd449ea7b4f069'
const OUT = fileURLToPath(new URL('../src/shopify-library/payment-icons.ts', import.meta.url))
// true when the probe probe-payment-icons shows Shopify printing a file db/payment_icons.yml does not list (`bogus`)
const ALL_FILES = true

const dir = process.argv[2]
if (!dir) throw new Error('usage: node bin/payment-icons.mjs <checkout of activemerchant/payment_icons>')
const head = execFileSync('git', ['-C', dir, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim()
if (head !== COMMIT) throw new Error(`${dir} is at ${head}, not ${COMMIT}`)
const icons = join(dir, 'app/assets/images/payment_icons')
const files = readdirSync(icons).filter(file => file.endsWith('.svg')).map(file => file.slice(0, -'.svg'.length))
const listed = [...readFileSync(join(dir, 'db/payment_icons.yml'), 'utf8').matchAll(/^\s*(?:-\s*)?name:\s*["']?([^"'\s]+)["']?\s*$/gm)].map(match => match[1])
if (new Set(listed).size !== listed.length) throw new Error('db/payment_icons.yml lists a name twice')
const missing = listed.filter(name => !files.includes(name))
if (missing.length) throw new Error(`no file for ${missing.join(', ')}`)
const names = [...(ALL_FILES ? files : listed)].sort()
const entries = names.map(name => `  ${JSON.stringify(name)}: ${JSON.stringify(readFileSync(join(icons, `${name}.svg`), 'utf8'))}`)
writeFileSync(OUT, `// Generated by bin/payment-icons.mjs from https://github.com/activemerchant/payment_icons at ${COMMIT} (MIT, Copyright 2015 Shopify Inc; see NOTICE.md); do not edit by hand.

/** Shopify's payment icons by payment type: each file app/assets/images/payment_icons/<type>.svg exactly as the repository holds it, its closing line break included, for every type ${ALL_FILES ? 'the folder holds' : 'db/payment_icons.yml lists'}. */
export const PAYMENT_ICONS: Readonly<Record<string, string>> = Object.freeze({
${entries.join(',\n')}
})
`)
console.log(`${OUT}: ${names.length} icons`)
